from sqlalchemy import JSON, Boolean, Integer, String, Text
from sqlalchemy.orm import Mapped, mapped_column

from app.models.base import Base, Timestamps, UUIDPk


class Company(UUIDPk, Timestamps, Base):
    """A tenant. Everything a company owns (users, customers, campaigns, chats...) carries its id."""

    __tablename__ = "companies"

    name: Mapped[str] = mapped_column(String(255))
    email: Mapped[str | None] = mapped_column(String(255))
    phone: Mapped[str | None] = mapped_column(String(32))
    website: Mapped[str | None] = mapped_column(String(255))
    address: Mapped[str | None] = mapped_column(Text)
    industry: Mapped[str | None] = mapped_column(String(128))
    # What the AI may tell customers about the company (voice agent + WhatsApp bot).
    description: Mapped[str | None] = mapped_column(Text)
    products_services: Mapped[str | None] = mapped_column(Text)
    timezone: Mapped[str] = mapped_column(String(64), default="Asia/Kolkata")  # "today" for the daily call limit
    is_active: Mapped[bool] = mapped_column(Boolean, default=True, server_default="true")

    # Limits set by the platform admin; None = unlimited.
    max_campaigns: Mapped[int | None] = mapped_column(Integer)
    daily_call_limit: Mapped[int | None] = mapped_column(Integer)
    max_concurrent_calls: Mapped[int | None] = mapped_column(Integer)

    # Which calling provider this company uses: "twilio" or "exotel". One at a time; the other
    # provider's saved details are kept but unused.
    telephony_provider: Mapped[str] = mapped_column(String(16), default="twilio", server_default="twilio")

    # The company's own Twilio account and caller id. Secrets are encrypted (services/crypto.py).
    twilio_account_sid: Mapped[str | None] = mapped_column(String(64))
    twilio_auth_token_enc: Mapped[str | None] = mapped_column(Text)
    # Unique: an inbound call is routed to its company by the number that was dialled.
    twilio_from_number: Mapped[str | None] = mapped_column(String(32), unique=True)

    # The company's own Exotel account. Calls run a flow the company built in Exotel (Voicebot applet ->
    # Passthru -> Hangup); exotel_app_id is that flow. exotel_secret is generated by us: the login
    # Exotel uses for the audio stream, and the source of the keys on its callbacks.
    exotel_api_key: Mapped[str | None] = mapped_column(String(128))
    exotel_api_token_enc: Mapped[str | None] = mapped_column(Text)
    exotel_account_sid: Mapped[str | None] = mapped_column(String(64))
    exotel_subdomain: Mapped[str] = mapped_column(String(64), default="api.in.exotel.com", server_default="api.in.exotel.com")
    exotel_number: Mapped[str | None] = mapped_column(String(32))  # the ExoPhone
    exotel_app_id: Mapped[str | None] = mapped_column(String(32))
    exotel_secret_enc: Mapped[str | None] = mapped_column(Text)

    # Inbound support calls on that same number. Both switches must be on: the platform admin allows
    # the feature, the company turns it on (which points its Twilio number at our inbound webhook).
    inbound_allowed: Mapped[bool] = mapped_column(Boolean, default=True, server_default="true")
    inbound_enabled: Mapped[bool] = mapped_column(Boolean, default=False, server_default="false")
    inbound_language: Mapped[str] = mapped_column(String(16), default="en-IN", server_default="en-IN")
    inbound_greeting: Mapped[str | None] = mapped_column(Text)  # empty = the default greeting
    # The languages a call may follow the caller into (speech codes like "ta-IN"). Empty = English and Hindi.
    inbound_languages: Mapped[list[str]] = mapped_column(JSON, default=list, server_default="[]")

    # The company's own WhatsApp Cloud API number. Inbound webhooks are routed by phone_number_id.
    whatsapp_phone_number_id: Mapped[str | None] = mapped_column(String(64), unique=True)
    whatsapp_access_token_enc: Mapped[str | None] = mapped_column(Text)
    whatsapp_app_secret_enc: Mapped[str | None] = mapped_column(Text)  # of the company's Meta app; required

    # Email support through the company's own SendGrid account. Customers write to email_address;
    # SendGrid's Inbound Parse posts those emails to our webhook (the address carries email_webhook_token),
    # and replies are sent from the same address with the company's API key. email_enabled is the
    # company's on/off switch: while it is off nothing is sent.
    email_enabled: Mapped[bool] = mapped_column(Boolean, default=False, server_default="false")
    email_address: Mapped[str | None] = mapped_column(String(255), unique=True)
    email_from_name: Mapped[str | None] = mapped_column(String(128))
    sendgrid_api_key_enc: Mapped[str | None] = mapped_column(Text)
    email_webhook_token: Mapped[str | None] = mapped_column(String(64), unique=True)

    # Set by billing while an invoice is unpaid past its due date and grace days: campaigns and
    # callbacks are held until it is paid. Inbound calls, WhatsApp and email are never held.
    billing_hold: Mapped[bool] = mapped_column(Boolean, default=False, server_default="false")
